import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import Ajv from 'ajv';
import formats from 'ajv-formats';
const ajv=new Ajv({strict:false});formats(ajv);
const valid=ajv.compile(JSON.parse(readFileSync('scripts/registry-schema.json')));
assert(valid(JSON.parse(readFileSync('server.json'))),JSON.stringify(valid.errors));
const pack=JSON.parse(readFileSync(process.argv[2]??'pack-dry-run.json'))[0];
const allowed=/^(dist\/[^/]+\.(js)|data\/(pokemon|source-sha256|pokeapi|pokeapi-sha256)\.json|README\.md|LICENSE|package\.json|server\.json)$/;
assert(pack.size<2_000_000);assert(pack.unpackedSize<2_000_000);
for(const f of pack.files)assert(allowed.test(f.path),`Unexpected packaged file: ${f.path}`);
assert(pack.files.some(f=>f.path==='dist/index.js'));assert(pack.files.some(f=>f.path==='data/pokemon.json'));
assert(readFileSync('dist/index.js','utf8').startsWith('#!/usr/bin/env node'));
console.log('PASS: official Registry schema; package allowlist, no images/secrets, executable shebang.');
